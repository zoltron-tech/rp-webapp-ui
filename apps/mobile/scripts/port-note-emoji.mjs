/**
 * Ports web's note emoji artwork to react-native-svg.
 *
 *   node apps/mobile/scripts/port-note-emoji.mjs
 *
 * The 34 note emoji are hand-drawn SVG in
 * `apps/web/src/app/rp/profile/edit/note-emoji-set.tsx`, stored on a note by
 * key. Every element they use (svg, defs, gradients, stop, path, circle,
 * ellipse, rect, line) has a react-native-svg counterpart with the same
 * props, so the port is a tag rename rather than a redraw — and re-running
 * this after the web set changes keeps the two identical.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const source = resolve(
  here,
  "../../web/src/app/rp/profile/edit/note-emoji-set.tsx",
);
const target = resolve(here, "../src/components/note-emoji.tsx");

const web = readFileSync(source, "utf8");

const TAGS = {
  circle: "Circle",
  defs: "Defs",
  ellipse: "Ellipse",
  line: "Line",
  linearGradient: "LinearGradient",
  path: "Path",
  radialGradient: "RadialGradient",
  rect: "Rect",
  stop: "Stop",
  svg: "Svg",
};

const start = web.indexOf("type SvgProps");
const end = web.indexOf("export type CustomEmoji");
if (start < 0 || end < 0) throw new Error("note-emoji-set.tsx changed shape");

const unknown = new Set(
  [...web.slice(start, end).matchAll(/<\/?([a-z][a-zA-Z]*)\b/g)]
    .map((match) => match[1])
    .filter((tag) => !(tag in TAGS)),
);
if (unknown.size) {
  throw new Error(`Unported SVG elements: ${[...unknown].join(", ")}`);
}

const icons = web
  .slice(start, end)
  .replace(
    /<(\/?)(circle|defs|ellipse|line|linearGradient|path|radialGradient|rect|stop|svg)\b/g,
    (_match, slash, tag) => `<${slash}${TAGS[tag]}`,
  );

const table = web.slice(end, web.indexOf("const EMOJI_BY_KEY"));

const output = `/**
 * The note emoji — web's \`note-emoji-set.tsx\`, drawn with react-native-svg.
 *
 * GENERATED by \`apps/mobile/scripts/port-note-emoji.mjs\`. Do not edit by
 * hand: change the web set and re-run the script, so both clients draw the
 * same artwork for the same stored key.
 */
/* biome-ignore-all lint: generated artwork */
import type { FC } from "react";
import { Text } from "react-native";
import Svg, {
  Circle,
  Defs,
  Ellipse,
  Line,
  LinearGradient,
  Path,
  RadialGradient,
  Rect,
  Stop,
} from "react-native-svg";

${icons}${table}const EMOJI_BY_KEY: Record<string, CustomEmoji> = Object.fromEntries(
  CUSTOM_EMOJI_SET.map((e) => [e.key, e]),
);

/**
 * A note emoji from its stored key. A legacy note that stored a literal
 * unicode emoji still shows, as text.
 */
export const NoteEmojiIcon: FC<{ emojiKey: string; size?: number }> = ({
  emojiKey,
  size = 20,
}) => {
  const found = EMOJI_BY_KEY[emojiKey];
  return found ? (
    <found.Icon size={size} />
  ) : (
    <Text style={{ fontSize: size * 0.85 }}>{emojiKey}</Text>
  );
};

/** Whether a note emoji is tilted when shown as a corner badge. */
export const getNoteEmojiRotate = (emojiKey: string): boolean =>
  EMOJI_BY_KEY[emojiKey]?.rotate ?? false;
`;

writeFileSync(target, output);
console.log(`Wrote ${target}`);
